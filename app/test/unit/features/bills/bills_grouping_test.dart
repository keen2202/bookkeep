Transaction t(
  int id,
  DateTime at, {
  TransactionType type = TransactionType.expense,
  int amountMinor = -100,
}) {
  return Transaction(
    id: id,
    bookId: testBookId,
    accountId: 1,
    categoryId: null,
    type: type,
    amountMinor: amountMinor,
    currency: 'CNY',
    rateSnapshot: 1000000,
    note: null,
    occurredAt: at,
    transferId: null,
    autoGenerated: false,
    updatedAt: at,
    deletedAt: null,
  );
